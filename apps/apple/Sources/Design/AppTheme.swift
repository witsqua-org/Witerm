/// The chosen theme. Views read it through `WitermTheme`, so a view that
/// draws with a theme color redraws when the theme changes (Observation).
@MainActor @Observable final class ThemeStore {
    static let shared = ThemeStore()

    var theme: AppTheme {
        didSet {
            guard theme != oldValue else { return }
            UserDefaults.standard.set(theme.rawValue, forKey: AppTheme.key)
            colors = ThemeColors(theme)
        }
    }
    private(set) var colors: ThemeColors

    private init() {
        let stored = UserDefaults.standard.string(forKey: AppTheme.key).flatMap(AppTheme.init(rawValue:)) ?? .standard
        theme = stored
        colors = ThemeColors(stored)
    }
}

/// A theme's colors as dynamic colors that resolve for the current light or
/// dark appearance and Increase Contrast. Made once per theme, so the same
/// theme always gives equal colors.
struct ThemeColors: Sendable {
    let canvas, surface, ink, secondary, accent, actionLabel: Color

    @MainActor private static var cache: [AppTheme: ThemeColors] = [:]

    @MainActor init(_ theme: AppTheme) {
        if let cached = Self.cache[theme] { self = cached; return }
        let light = theme.chrome(dark: false), dark = theme.chrome(dark: true)
        let high = AppTheme.highContrast
        func color(_ key: KeyPath<AppTheme.Chrome, UInt32>) -> Color {
            Self.dynamic(light: light[keyPath: key], dark: dark[keyPath: key],
                         highLight: high.light[keyPath: key], highDark: high.dark[keyPath: key])
        }
        canvas = color(\.canvas)
        surface = color(\.surface)
        ink = color(\.ink)
        secondary = color(\.secondary)
        accent = color(\.accent)
        actionLabel = color(\.actionLabel)
        Self.cache[theme] = self
    }

    private static func dynamic(light: UInt32, dark: UInt32, highLight: UInt32, highDark: UInt32) -> Color {
        #if os(macOS)
        Color(nsColor: NSColor(name: nil) { appearance in
            switch appearance.bestMatch(from: [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua]) {
            case .darkAqua: NSColor(terminalRGB: dark)
            case .accessibilityHighContrastAqua: NSColor(terminalRGB: highLight)
            case .accessibilityHighContrastDarkAqua: NSColor(terminalRGB: highDark)
            default: NSColor(terminalRGB: light)
            }
        })
        #else
        Color(uiColor: UIColor { traits in
            let isDark = traits.userInterfaceStyle == .dark
            if traits.accessibilityContrast == .high { return UIColor(terminalRGB: isDark ? highDark : highLight) }
            return UIColor(terminalRGB: isDark ? dark : light)
        })
        #endif
    }
}
